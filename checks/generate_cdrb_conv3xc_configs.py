"""Generate seven static SVRDD YAMLs alongside the existing official baseline."""

from copy import deepcopy
from pathlib import Path

import yaml


MODEL_DIR = Path(__file__).resolve().parents[1] / 'ultralytics/cfg/models/rt-detr'
CONTROL = MODEL_DIR / 'resnet18-SVRDD-baseline.yaml'
VARIANTS = (
    'scsa', 'cdrb', 'conv3xc', 'scsa-cdrb', 'scsa-conv3xc',
    'cdrb-conv3xc', 'scsa-cdrb-conv3xc',
)


def main():
    control = yaml.safe_load(CONTROL.read_text(encoding='utf-8'))
    for name in VARIANTS:
        config = deepcopy(control)
        factors = set(name.split('-'))
        if 'cdrb' in factors:
            block = 'BasicBlock_CDRB'
        elif 'scsa' in factors:
            block = 'BasicBlock_SCSA'
        else:
            block = 'BasicBlock'
        for stage in config['backbone'][4:8]:
            stage[3][1] = block
            stage[3][3] = 'scsa' in factors
        if 'conv3xc' in factors:
            # Only the P3 top-down RepC3, i.e. global layer 19 / head index 11.
            config['head'][11][2] = 'RepC3_Conv3XC'
        path = MODEL_DIR / f'rtdetr-resnet18-svrdd-{name}.yaml'
        path.write_text(f'# SVRDD chapter-3 factors: {name}; P3/P4/P5 unchanged.\n'
                        + '# Generated by checks/generate_cdrb_conv3xc_configs.py.\n'
                        + yaml.safe_dump(config, allow_unicode=True, sort_keys=False), encoding='utf-8')
        print(path.name)


if __name__ == '__main__':
    main()
