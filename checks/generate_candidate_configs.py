"""Regenerate the nine static YAMLs for the two thesis candidate matrices.

Run from the repository root: python checks/generate_candidate_configs.py
Existing baseline/SCSA/FreqFusion/DySample YAMLs remain the controls.
"""

from copy import deepcopy
from pathlib import Path

import yaml


MODEL_DIR = Path(__file__).resolve().parents[1] / 'ultralytics/cfg/models/rt-detr'
BASES = {
    'baseline': 'rtdetr-resnet18.yaml',
    'scsa': 'rtdetr-resnet18-SCSA.yaml',
    'freqfusion': 'rtdetr-resnet18-FreqFusion-P3.yaml',
    'scsa-freqfusion': 'rtdetr-resnet18-SCSA-FreqFusion-P3.yaml',
    'dysample': 'rtdetr-resnet18-DySample.yaml',
}
NEW = {
    'scale-decoder': ('baseline', False, False, True),
    'scsa-scale-decoder': ('scsa', False, False, True),
    'freqfusion-scale-decoder': ('freqfusion', False, False, True),
    'scsa-freqfusion-scale-decoder': ('scsa-freqfusion', False, False, True),
    'fdconv-c4': ('baseline', False, True, False),
    'scsa-dysample': ('dysample', True, False, False),
    'scsa-fdconv-c4': ('scsa', False, True, False),
    'dysample-fdconv-c4': ('dysample', False, True, False),
    'scsa-dysample-fdconv-c4': ('dysample', True, True, False),
}


def main():
    scsa_backbone = yaml.safe_load((MODEL_DIR / BASES['scsa']).read_text(encoding='utf-8'))['backbone']
    for name, (base, scsa, fdconv, scale_decoder) in NEW.items():
        model = deepcopy(yaml.safe_load((MODEL_DIR / BASES[base]).read_text(encoding='utf-8')))
        if scsa:
            model['backbone'] = deepcopy(scsa_backbone)
        if fdconv:
            model['backbone'][6][2] = 'BlocksFDConvC4'
        if scale_decoder:
            model['head'][-1][3][3] = [6, 4, 2]
        path = MODEL_DIR / f'rtdetr-resnet18-{name}.yaml'
        path.write_text(f'# Thesis candidate: {name}. Generated by checks/generate_candidate_configs.py.\n'
                        + yaml.safe_dump(model, allow_unicode=True, sort_keys=False), encoding='utf-8')
        print(path.name)


if __name__ == '__main__':
    main()
